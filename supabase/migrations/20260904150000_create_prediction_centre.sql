create or replace function public.validate_prediction_vote()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  matchup public.prediction_matchups;
  lock_time timestamptz;
begin
  select * into matchup
  from public.prediction_matchups
  where id = new.matchup_id;

  if not found then
    raise exception 'Prediction matchup does not exist';
  end if;

  select locks_at into lock_time
  from public.prediction_weeks
  where id = matchup.prediction_week_id;

  if now() >= lock_time then
    raise exception 'Predictions are locked for this week';
  end if;

  if new.selected_roster_id not in (
    matchup.home_roster_id,
    matchup.away_roster_id
  ) then
    raise exception 'Selected roster is not part of this matchup';
  end if;

  new.updated_at = now();
  return new;
end;
$$;

create trigger prediction_votes_validate
before insert or update on public.prediction_votes
for each row execute function public.validate_prediction_vote();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (
    id,
    login_slug,
    display_name,
    sleeper_user_id,
    roster_id,
    franchise_id,
    is_admin
  ) values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'login_slug', ''),
      split_part(new.email, '@', 1)
    ),
    coalesce(
      nullif(new.raw_user_meta_data ->> 'display_name', ''),
      split_part(new.email, '@', 1)
    ),
    nullif(new.raw_user_meta_data ->> 'sleeper_user_id', ''),
    nullif(new.raw_user_meta_data ->> 'roster_id', '')::smallint,
    nullif(new.raw_user_meta_data ->> 'franchise_id', ''),
    coalesce((new.raw_user_meta_data ->> 'is_admin')::boolean, false)
  )
  on conflict (id) do update set
    login_slug = excluded.login_slug,
    display_name = excluded.display_name,
    sleeper_user_id = excluded.sleeper_user_id,
    roster_id = excluded.roster_id,
    franchise_id = excluded.franchise_id,
    is_admin = excluded.is_admin;

  return new;
end;
$$;

create trigger on_auth_user_created
after insert or update of raw_user_meta_data on auth.users
for each row execute function public.handle_new_user();

