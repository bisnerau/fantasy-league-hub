create policy "Members see their own picks before lock and all picks after lock"
on public.prediction_votes for select
to authenticated
using (
  voter_id = auth.uid()
  or exists (
    select 1
    from public.prediction_matchups matchup
    join public.prediction_weeks prediction_week
      on prediction_week.id = matchup.prediction_week_id
    where matchup.id = prediction_votes.matchup_id
      and now() >= prediction_week.locks_at
  )
);

create policy "Members can cast their own picks before lock"
on public.prediction_votes for insert
to authenticated
with check (
  voter_id = auth.uid()
  and exists (
    select 1
    from public.prediction_matchups matchup
    join public.prediction_weeks prediction_week
      on prediction_week.id = matchup.prediction_week_id
    where matchup.id = prediction_votes.matchup_id
      and selected_roster_id in (
        matchup.home_roster_id,
        matchup.away_roster_id
      )
      and now() < prediction_week.locks_at
  )
);

create policy "Members can change their own picks before lock"
on public.prediction_votes for update
to authenticated
using (
  voter_id = auth.uid()
  and exists (
    select 1
    from public.prediction_matchups matchup
    join public.prediction_weeks prediction_week
      on prediction_week.id = matchup.prediction_week_id
    where matchup.id = prediction_votes.matchup_id
      and now() < prediction_week.locks_at
  )
)
with check (
  voter_id = auth.uid()
  and exists (
    select 1
    from public.prediction_matchups matchup
    join public.prediction_weeks prediction_week
      on prediction_week.id = matchup.prediction_week_id
    where matchup.id = prediction_votes.matchup_id
      and selected_roster_id in (
        matchup.home_roster_id,
        matchup.away_roster_id
      )
      and now() < prediction_week.locks_at
  )
);

create view public.prediction_leaderboard
with (security_invoker = true)
as
select
  profile.id as voter_id,
  profile.display_name,
  count(matchup.id) filter (
    where matchup.winner_roster_id is not null
  )::integer as completed_picks,
  count(matchup.id) filter (
    where vote.selected_roster_id = matchup.winner_roster_id
  )::integer as correct_picks,
  coalesce(
    round(
      100.0 * count(matchup.id) filter (
        where vote.selected_roster_id = matchup.winner_roster_id
      ) / nullif(
        count(matchup.id) filter (
          where matchup.winner_roster_id is not null
        ),
        0
      ),
      1
    ),
    0
  ) as accuracy
from public.profiles profile
left join public.prediction_votes vote on vote.voter_id = profile.id
left join public.prediction_matchups matchup
  on matchup.id = vote.matchup_id
group by profile.id, profile.display_name;

