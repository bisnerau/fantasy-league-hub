create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  login_slug text not null unique,
  display_name text not null,
  sleeper_user_id text unique,
  roster_id smallint unique,
  franchise_id text unique,
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.prediction_weeks (
  id bigint generated by default as identity primary key,
  league_id text not null,
  season smallint not null,
  week smallint not null check (week between 1 and 18),
  locks_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (league_id, season, week)
);

create table public.prediction_matchups (
  id bigint generated by default as identity primary key,
  prediction_week_id bigint not null references public.prediction_weeks(id) on delete cascade,
  sleeper_matchup_id smallint not null,
  home_roster_id smallint not null,
  away_roster_id smallint not null,
  home_projected numeric(6, 2) not null default 0,
  away_projected numeric(6, 2) not null default 0,
  home_final numeric(6, 2),
  away_final numeric(6, 2),
  winner_roster_id smallint,
  status text not null default 'scheduled' check (status in ('scheduled', 'locked', 'final')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (home_roster_id <> away_roster_id),
  check (
    winner_roster_id is null
    or winner_roster_id in (home_roster_id, away_roster_id)
  ),
  unique (prediction_week_id, sleeper_matchup_id)
);

create table public.prediction_votes (
  matchup_id bigint not null references public.prediction_matchups(id) on delete cascade,
  voter_id uuid not null references public.profiles(id) on delete cascade,
  selected_roster_id smallint not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (matchup_id, voter_id)
);

create index prediction_matchups_week_idx
  on public.prediction_matchups (prediction_week_id);

create index prediction_votes_voter_idx
  on public.prediction_votes (voter_id);

